# operasi aritmatika 

a = 21
b = 4

# pertambahan +
pertambahan = a + b 
print("a + B = ", pertambahan) 


#pengurangan -
pengurangan = a - b
print("a - b =", pengurangan)


#perkalian *    
perkalian = a * b
print("a x b =", perkalian)

#eksponen **
eksponen = a ** b
print("10 pangkat 3=", eksponen)

# pembagian
pembagian = a / b
print("a : b =", pembagian)

#modulus (sisa pembagian) %
eksponen = a % b
print(a,'%', b,'=', eksponen)

#floor division ( hasil pembagian yang dibulatkan ke bawah)
floor = a // b
print(floor)

# prioritas operasi, OPERATIONAL PRECEDENCE

x = 3
y = 2 
z = 4 

hasil = x ** y * z + x / y - y % z  // x
print(x, '**' ,y, '*' , z, '+' , x,  '/' , y, '-' , y,  '%' , z, '//' , x, '=', hasil)